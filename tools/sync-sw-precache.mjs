/**
 * Пересобирает список прекеша в sw.js по реальному содержимому репозитория:
 * все подключения из index.html плюс всё, что лежит в assets/.
 *
 * Имя кэша получает хеш от содержимого этих файлов, поэтому любая правка
 * ассета сама инвалидирует старый кэш у пользователей.
 *
 * Запуск из корня: node tools/sync-sw-precache.mjs
 * С флагом --check ничего не пишет, а падает, если sw.js устарел.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { glob } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SW = join(ROOT, 'sw.js');
const CACHE_PREFIX = 'sale';

const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const refs = [...html.matchAll(/<(?:script|link)[^>]+(?:src|href)="([^"]+)"/g)]
  .map((m) => m[1])
  .filter((p) => !/^https?:\/\//.test(p) && p !== 'manifest.webmanifest');

const assets = [];
for await (const file of glob('assets/**/*', { cwd: ROOT, withFileTypes: true })) {
  if (file.isFile()) assets.push(join(file.parentPath, file.name));
}
const assetPaths = assets
  .map((p) => p.slice(ROOT.length + 1).split('\\').join('/'))
  // *_meta.json — раскладка кадров для сборщика атласов, в рантайме не грузится
  .filter((p) => !p.endsWith('_meta.json'))
  .sort();

const list = [...new Set(['index.html', 'manifest.webmanifest', ...refs, ...assetPaths])];

const hash = createHash('sha1');
for (const rel of list) hash.update(rel).update(readFileSync(join(ROOT, rel)));
const version = hash.digest('hex').slice(0, 10);

const body = list.map((p) => `  '${p}',`).join('\n');
const block = [
  `const CACHE = '${CACHE_PREFIX}-${version}';`,
  '',
  '// >>> generated by tools/sync-sw-precache.mjs — правится скриптом, не руками',
  'const ASSETS = [',
  body,
  '].map((p) => new URL(p, BASE).href);',
  '// <<< generated',
].join('\n');

const sw = readFileSync(SW, 'utf8');
const next = sw.replace(
  /const CACHE = '[^']*';[\s\S]*?\/\/ <<< generated/,
  block,
);
if (!/const CACHE = '[^']*';[\s\S]*?\/\/ <<< generated/.test(sw)) {
  throw new Error('sw.js: не нашёл блок между "const CACHE" и "// <<< generated"');
}

if (process.argv.includes('--check')) {
  if (next !== sw) {
    console.error('sw.js устарел — запусти: node tools/sync-sw-precache.mjs');
    process.exit(1);
  }
  console.log(`sw.js в актуальном состоянии (${list.length} files)`);
} else {
  writeFileSync(SW, next);
  console.log(`sw.js: ${list.length} files, cache ${CACHE_PREFIX}-${version}`);
}
